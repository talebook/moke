import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import test from 'node:test';

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const readJson = (path) => JSON.parse(read(path));

const buildSource = read('src-tauri/build.rs');
const extensionsSource = read('src-tauri/src/extensions/mod.rs');
const extensionsStore = read('src/lib/store/extensions.ts');

function appAclCommands(source) {
  const block = source.match(/const APP_ACL_COMMANDS:.*?= &\[([\s\S]*?)\n\];/)?.[1];
  assert.ok(block, 'APP_ACL_COMMANDS must remain a literal list for contract validation');
  return [...block.matchAll(/"([a-z0-9_]+)"/g)].map((match) => match[1]);
}

function extensionHandlerCommands(source) {
  const handler = source.indexOf('pub fn invoke_handler');
  assert.notEqual(handler, -1, 'extensions::invoke_handler is missing');
  const macro = source.indexOf('tauri::generate_handler![', handler);
  assert.notEqual(macro, -1, 'extensions::invoke_handler must register through generate_handler!');
  const block = source.slice(macro, source.indexOf(']', macro));
  return [...new Set([...block.matchAll(/\b(ext_[a-z0-9_]+)\b/g)].map((match) => match[1]))];
}

// Commands the shell invokes directly. The extension iframe is a remote origin
// without the Tauri IPC bridge, so it talks to its own backend over HTTP instead.
const shellCommands = [
  ...new Set(
    [...extensionsStore.matchAll(/invokeExt(?:<[^>]*>)?\(\s*'(ext_[a-z0-9_]+)'/g)].map((match) => match[1]),
  ),
];

const handlerCommands = extensionHandlerCommands(extensionsSource);
const aclCommands = new Set(appAclCommands(buildSource));
const allowPermission = (command) => `allow-${command.replaceAll('_', '-')}`;
const capabilityPermissions = (path) => readJson(path).permissions.map(
  (permission) => (typeof permission === 'string' ? permission : permission.identifier),
);

test('every extension host command is declared in the app ACL manifest', () => {
  assert.ok(handlerCommands.includes('ext_reader_event'));
  assert.ok(shellCommands.length > 0, 'the extension store must invoke host commands');
  for (const command of handlerCommands) {
    assert.ok(
      aclCommands.has(command),
      `${command} must be declared in APP_ACL_COMMANDS, otherwise Tauri rejects it before the handler runs`,
    );
    const permission = `src-tauri/permissions/autogenerated/${command}.toml`;
    assert.ok(existsSync(new URL(`../${permission}`, import.meta.url)), `${permission} must be generated and committed`);
    assert.match(read(permission), new RegExp(`identifier = "allow-${command.replaceAll('_', '-')}"`));
  }
});

test('the desktop shell lists and manages extensions through the ACL', () => {
  assert.deepEqual(shellCommands.sort(), [
    'ext_disable_extension',
    'ext_enable_extension',
    'ext_list_extensions',
    'ext_uninstall_extension',
  ]);
  for (const file of [
    'src-tauri/capabilities/default.json',
  ]) {
    const permissions = capabilityPermissions(file);
    for (const command of shellCommands) {
      assert.ok(
        permissions.includes(allowPermission(command)),
        `${file} must grant ${allowPermission(command)} to the main window`,
      );
    }
  }
});

test('desktop-only extension commands stay out of mobile and OHOS capabilities', () => {
  for (const file of [
    'src-tauri/capabilities/ohos.json',
    'src-tauri/capabilities/reader-mobile.json',
    'src-tauri/capabilities/reader.json',
    'src-tauri/capabilities/reader-android-navigation.json',
  ]) {
    const permissions = capabilityPermissions(file);
    for (const command of shellCommands) {
      assert.ok(
        !permissions.includes(allowPermission(command)),
        `${file} must not grant ${allowPermission(command)}; the command is not registered on that runtime`,
      );
    }
  }
});
